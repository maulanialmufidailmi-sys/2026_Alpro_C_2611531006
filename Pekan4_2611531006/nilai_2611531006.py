nilai_1006= int(input("Inputkan nilai angka= "))

if nilai_1006 > 81:
    print("A")
elif nilai_1006 > 78:
    print("B")
elif nilai_1006 > 60:
    print("C")
elif nilai_1006 >= 50:
    print("D")
else:
    print("E")
